def russian_reference_case(source, form):
    import re
    value = str(source or '').strip().lower()
    if not value:
        return ''
    if value == 'приемное':
        value = 'приемное отделение'
    found = False
    result = []
    for word in value.split():
        if found:
            result.append(word)
            continue
        parts = word.split('-')
        if all(part in HEADS for part in parts):
            found = True
            word = '-'.join(HEADS[part][0 if form == 'genitive' else 1] for part in parts)
        elif word.endswith('ая'):
            word = word[:-2] + 'ой'
        elif word.endswith('яя'):
            word = word[:-2] + 'ей'
        elif re.search('(ый|ой|ое)$', word):
            word = word[:-2] + ('ого' if form == 'genitive' else 'ому')
        elif re.search('(ий|ее)$', word):
            word = word[:-2] + ('его' if form == 'genitive' else 'ему')
        elif word.endswith('ия'):
            found = True
            word = word[:-1] + 'и'
        elif re.search('(ение|ание)$', word):
            found = True
            word = word[:-1] + ('я' if form == 'genitive' else 'ю')
        elif word.endswith('ство'):
            found = True
            word = word[:-1] + ('а' if form == 'genitive' else 'у')
        result.append(word)
    return ' '.join(result) if found else ''
