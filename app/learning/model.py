"""Portable tables permit an isolated SQLite end-to-end pilot test."""
from sqlalchemy import Boolean, CheckConstraint, Column, DateTime, ForeignKey, Integer, MetaData, String, Table, Text, UniqueConstraint, func

metadata = MetaData()
records = Table("learning_records", metadata,
    Column("id", String(36), primary_key=True), Column("participant_id", Integer, nullable=False),
    Column("unit_id", Integer, nullable=False), Column("application_ref", String(100), nullable=False),
    Column("action", String(30), nullable=False), Column("detail", Text, nullable=False, default=""),
    Column("created_at", DateTime(timezone=True), nullable=False, server_default=func.now()),
    CheckConstraint("action IN ('opened','approved','rejected','visa_viewed','submitted')"),
)
attempts = Table("learning_attempts", metadata,
    Column("id", String(36), primary_key=True), Column("participant_id", Integer, nullable=False),
    Column("unit_id", Integer, nullable=False), Column("lesson_code", String(50), nullable=False),
    Column("record_id", String(36), ForeignKey("learning_records.id"), nullable=False),
    Column("attempt_no", Integer, nullable=False), Column("status", String(30), nullable=False),
    Column("pre_score", Integer, nullable=True), Column("pre_required", Boolean, nullable=True),
    Column("score", Integer, nullable=True), Column("required_met", Boolean, nullable=True),
    Column("reviewer_id", Integer, nullable=True), Column("reviewed_at", DateTime(timezone=True), nullable=True),
    Column("review_note", Text, nullable=False, default=""),
    Column("review_source", String(20), nullable=True),
    Column("auto_status", String(20), nullable=False, default="unavailable"),
    Column("auto_note", Text, nullable=False, default=""),
    Column("lesson_snapshot_json", Text, nullable=True),
    Column("created_at", DateTime(timezone=True), nullable=False, server_default=func.now()),
    UniqueConstraint("participant_id", "unit_id", "lesson_code", "attempt_no"),
    CheckConstraint("score IS NULL OR score BETWEEN 0 AND 5"),
    CheckConstraint("pre_score IS NULL OR pre_score BETWEEN 0 AND 5"),
)
screenshots = Table("learning_screenshots", metadata,
    Column("id", String(36), primary_key=True), Column("attempt_id", String(36), ForeignKey("learning_attempts.id"), nullable=False),
    Column("participant_id", Integer, nullable=False), Column("record_id", String(36), ForeignKey("learning_records.id"), nullable=False),
    Column("storage_key", String(36), nullable=False, unique=True), Column("mime", String(30), nullable=False),
    Column("checksum", String(64), nullable=False), Column("bytes", Integer, nullable=False),
    Column("created_at", DateTime(timezone=True), nullable=False, server_default=func.now()),
)
screenshot_slots = Table("learning_screenshot_slots", metadata,
    Column("screenshot_id", String(36), ForeignKey("learning_screenshots.id"), primary_key=True),
    Column("attempt_id", String(36), ForeignKey("learning_attempts.id"), nullable=False),
    Column("slot", Integer, nullable=False),
    UniqueConstraint("attempt_id", "slot"),
    CheckConstraint("slot >= 0"),
)
criterion_results = Table("learning_criterion_results", metadata,
    Column("attempt_id", String(36), ForeignKey("learning_attempts.id"), primary_key=True),
    Column("criterion_no", Integer, primary_key=True),
    Column("met", Boolean, nullable=False),
)
exercise_applications = Table("learning_exercise_applications", metadata,
    Column("id", String(36), primary_key=True),
    Column("attempt_id", String(36), ForeignKey("learning_attempts.id"), nullable=False, unique=True),
    Column("participant_id", Integer, nullable=False), Column("unit_id", Integer, nullable=False),
    Column("application_ref", String(100), nullable=False, unique=True),
    Column("candidate_name", String(120), nullable=False), Column("position_title", String(120), nullable=False),
    Column("employment_fraction", String(20), nullable=False), Column("start_date", String(20), nullable=False),
    Column("status", String(30), nullable=False),
    Column("approved_at", DateTime(timezone=True), nullable=True),
    Column("created_at", DateTime(timezone=True), nullable=False, server_default=func.now()),
    CheckConstraint("status IN ('awaiting_consent','approved')"),
)

courses = Table("learning_courses", metadata,
    Column("code", String(50), primary_key=True), Column("title", String(200), nullable=False),
    Column("audience", String(120), nullable=False, default=""),
    Column("state", String(20), nullable=False, default="draft"),
    Column("created_by", Integer, nullable=False),
    Column("created_at", DateTime(timezone=True), nullable=False, server_default=func.now()),
    Column("updated_at", DateTime(timezone=True), nullable=False, server_default=func.now()),
    CheckConstraint("state IN ('draft','published')"),
)
lessons = Table("learning_lessons", metadata,
    Column("code", String(50), primary_key=True),
    Column("course_code", String(50), nullable=False),
    Column("title", String(200), nullable=False),
    Column("target_role", String(120), nullable=False),
    Column("minutes", Integer, nullable=False),
    Column("task", Text, nullable=False),
    Column("instruction", Text, nullable=False, default=""),
    Column("guide_url", Text, nullable=False, default=""),
    Column("criteria_json", Text, nullable=False),
    Column("required_index", Integer, nullable=False),
    Column("screenshots_json", Text, nullable=False),
    Column("state", String(20), nullable=False, default="draft"),
    Column("created_by", Integer, nullable=False),
    Column("created_at", DateTime(timezone=True), nullable=False, server_default=func.now()),
    Column("updated_at", DateTime(timezone=True), nullable=False, server_default=func.now()),
    CheckConstraint("minutes BETWEEN 1 AND 480"),
    CheckConstraint("state IN ('draft','published')"),
)
assignment_batches = Table("learning_assignment_batches", metadata,
    Column("id", String(36), primary_key=True),
    Column("target_type", String(20), nullable=False),
    Column("target_code", String(50), nullable=False),
    Column("selector_json", Text, nullable=False),
    Column("recipients_json", Text, nullable=False),
    Column("due_at", DateTime(timezone=True), nullable=True),
    Column("created_by", Integer, nullable=False),
    Column("created_at", DateTime(timezone=True), nullable=False, server_default=func.now()),
    CheckConstraint("target_type IN ('course','lesson')"),
)
assignments = Table("learning_assignments", metadata,
    Column("id", String(36), primary_key=True),
    Column("batch_id", String(36), ForeignKey("learning_assignment_batches.id"), nullable=False),
    Column("lesson_code", String(50), nullable=False),
    Column("participant_id", Integer, nullable=False),
    Column("unit_id", Integer, nullable=False),
    Column("recipient_name", String(200), nullable=False),
    Column("position_name", String(120), nullable=False),
    Column("due_at", DateTime(timezone=True), nullable=True),
    Column("created_at", DateTime(timezone=True), nullable=False, server_default=func.now()),
    UniqueConstraint("lesson_code", "participant_id"),
)
review_events = Table("learning_review_events", metadata,
    Column("id", String(36), primary_key=True),
    Column("attempt_id", String(36), ForeignKey("learning_attempts.id"), nullable=False),
    Column("source", String(20), nullable=False),
    Column("old_status", String(30), nullable=True),
    Column("old_score", Integer, nullable=True),
    Column("new_status", String(30), nullable=False),
    Column("new_score", Integer, nullable=False),
    Column("criteria_json", Text, nullable=False),
    Column("note", Text, nullable=False, default=""),
    Column("reason", Text, nullable=False, default=""),
    Column("actor_id", Integer, nullable=True),
    Column("created_at", DateTime(timezone=True), nullable=False, server_default=func.now()),
    CheckConstraint("source IN ('manual','automatic')"),
)

hire_applications = Table("learning_hire_applications", metadata,
    Column("attempt_id", String(36), ForeignKey("learning_attempts.id"), primary_key=True),
    Column("participant_id", Integer, nullable=False),
    Column("unit_id", Integer, nullable=False),
    Column("application_id", Integer, nullable=False, unique=True),
    Column("person_id", Integer, nullable=False),
    Column("fixture_json", Text, nullable=False),
    Column("created_at", DateTime(timezone=True), nullable=False, server_default=func.now()),
)

# The rehearsal chain is keyed by the original hire application attempt.  Its
# recipient and messages are separate from the operational personnel tables.
hire_step_links = Table("learning_hire_step_links", metadata,
    Column("attempt_id", String(36), ForeignKey("learning_attempts.id"), primary_key=True),
    Column("root_attempt_id", String(36), ForeignKey("learning_attempts.id"), nullable=False),
    Column("step", Integer, nullable=False),
    Column("created_at", DateTime(timezone=True), nullable=False, server_default=func.now()),
    CheckConstraint("step BETWEEN 2 AND 5"),
)
hire_recipients = Table("learning_hire_recipients", metadata,
    Column("root_attempt_id", String(36), ForeignKey("learning_attempts.id"), primary_key=True),
    Column("candidate_user_id", Integer, nullable=False),
    Column("employee_id", Integer, nullable=True),
    Column("created_at", DateTime(timezone=True), nullable=False, server_default=func.now()),
)
hire_messages = Table("learning_hire_messages", metadata,
    Column("id", String(36), primary_key=True),
    Column("root_attempt_id", String(36), ForeignKey("learning_attempts.id"), nullable=False),
    Column("recipient_user_id", Integer, nullable=False),
    Column("kind", String(30), nullable=False),
    Column("link_id", Integer, nullable=True),
    Column("order_id", Integer, nullable=True),
    Column("created_by_user_id", Integer, nullable=False),
    Column("created_at", DateTime(timezone=True), nullable=False, server_default=func.now()),
    CheckConstraint("kind IN ('intake_link','order_notice')"),
    UniqueConstraint("root_attempt_id", "kind", "link_id"),
)
hire_acknowledgements = Table("learning_hire_acknowledgements", metadata,
    Column("root_attempt_id", String(36), ForeignKey("learning_attempts.id"), primary_key=True),
    Column("order_id", Integer, nullable=False),
    Column("employee_id", Integer, nullable=False),
    Column("recipient_user_id", Integer, nullable=False),
    Column("method", String(30), nullable=False),
    Column("evidence", Text, nullable=False),
    Column("acknowledged_at", DateTime(timezone=True), nullable=False, server_default=func.now()),
)
hire_signatures = Table("learning_hire_signatures", metadata,
    Column("root_attempt_id", String(36), ForeignKey("learning_attempts.id"), primary_key=True),
    Column("order_id", Integer, nullable=False),
    Column("signatory_user_id", Integer, nullable=False),
    Column("signed_at", DateTime(timezone=True), nullable=False, server_default=func.now()),
)
