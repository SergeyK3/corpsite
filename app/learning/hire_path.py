def step_for_lesson(lesson: dict) -> int | None:
    if lesson.get("course_code") != COURSE_CODE:
        return None
    if lesson.get("title") == FIRST_TITLE and lesson.get("target_role") == FIRST_ROLE:
        return 1
    return STEP_BY_CODE.get(lesson.get("code"))
