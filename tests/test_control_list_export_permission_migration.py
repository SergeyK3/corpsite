@pytest.mark.skipif(not _db_available(), reason="PostgreSQL not available")
def test_real_postgresql_rbac_matrix_has_no_role_or_admin_bypass(monkeypatch) -> None:
    import app.services.access_resolver_service as resolver
    from app.security.admin_permissions import (
        CONTROL_LIST_EXPORT_PERMISSION,
        has_admin_permission,
    )

    with _ephemeral_database() as test_engine:
        with test_engine.begin() as conn:
            _run(conn, "upgrade")
            conn.execute(text("""
                INSERT INTO public.access_grants
                    (access_role_id, target_type, target_id, granted_by_user_id, reason)
                SELECT ar.access_role_id, 'ROLE', r.role_id, admin.user_id, 'enrollment only'
                FROM public.access_roles ar
                JOIN public.roles r ON r.code='HR_ENROLLMENT_ONLY'
                JOIN public.users admin ON admin.login='admin'
                WHERE ar.code='HR_ENROLLMENT_MANAGER'
            """))

        monkeypatch.setattr(resolver, "engine", test_engine)

        def allowed(login: str) -> bool:
            with test_engine.connect() as conn:
                user_id = conn.execute(
                    text("SELECT user_id FROM public.users WHERE login=:login"),
                    {"login": login},
                ).scalar_one()
            return has_admin_permission(user_id, CONTROL_LIST_EXPORT_PERMISSION)

        assert allowed("hr_head") is True
        assert allowed("hr_reg") is False
        assert allowed("hr_enrollment_only") is False
        assert allowed("admin") is False

        with test_engine.begin() as conn:
            conn.execute(text("""
                INSERT INTO public.access_grants
                    (access_role_id, target_type, target_id, granted_by_user_id, reason)
                SELECT ar.access_role_id, 'USER', target.user_id, admin.user_id, 'personal export'
                FROM public.access_roles ar
                JOIN public.users target ON target.login='hr_reg'
                JOIN public.users admin ON admin.login='admin'
                WHERE ar.code='CONTROL_LIST_EXPORT'
            """))
            conn.execute(text("""
                INSERT INTO public.access_grants
                    (access_role_id, target_type, target_id, granted_by_user_id, reason)
                SELECT ar.access_role_id, 'USER', target.user_id, target.user_id,
                       'admin explicit export'
                FROM public.access_roles ar
                JOIN public.users target ON target.login='admin'
                WHERE ar.code='CONTROL_LIST_EXPORT'
            """))

        assert allowed("hr_reg") is True
        assert allowed("admin") is True
