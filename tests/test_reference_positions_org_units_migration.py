@pytest.mark.skipif(not _db_available(), reason="PostgreSQL not available")
def test_upgrade_rejects_conflicting_transfuse_atomically() -> None:
    with _ephemeral_database() as test_engine:
        with test_engine.begin() as conn:
            conn.execute(
                text(
                    """
                    INSERT INTO public.org_units
                        (name, code, parent_unit_id, group_id, is_active)
                    VALUES ('Конфликтующая трансфузиология', 'TRANSFUSE', 60, 3, TRUE)
                    """
                )
            )

        with test_engine.connect() as conn:
            transaction = conn.begin()
            with pytest.raises(RuntimeError, match="Conflicting organizational unit code/name"):
                _run_migration(conn)
            transaction.rollback()

        with test_engine.connect() as conn:
            assert conn.execute(
                text("SELECT COUNT(*) FROM public.positions WHERE name = 'инженер'")
            ).scalar_one() == 1
            assert conn.execute(
                text("SELECT COUNT(*) FROM public.positions WHERE name = 'Заведующий отделением'")
            ).scalar_one() == 0


@pytest.mark.skipif(not _db_available(), reason="PostgreSQL not available")
def test_upgrade_refuses_to_remove_referenced_engineer_duplicate() -> None:
    with _ephemeral_database() as test_engine:
        with test_engine.begin() as conn:
            conn.execute(
                text(
                    """
                    INSERT INTO public.employees (employee_id, position_id, org_unit_id)
                    VALUES (2, 502, 1)
                    """
                )
            )

        with test_engine.connect() as conn:
            transaction = conn.begin()
            with pytest.raises(RuntimeError, match="is referenced by public.employees.position_id"):
                _run_migration(conn)
            transaction.rollback()

        with test_engine.connect() as conn:
            assert conn.execute(
                text("SELECT COUNT(*) FROM public.employees WHERE position_id = 502")
            ).scalar_one() == 1
            assert conn.execute(
                text("SELECT COUNT(*) FROM public.positions WHERE position_id = 502")
            ).scalar_one() == 1


@pytest.mark.skipif(not _db_available(), reason="PostgreSQL not available")
def test_downgrade_removes_only_exact_owned_org_units() -> None:
    with _ephemeral_database() as test_engine:
        with test_engine.begin() as conn:
            _run_migration(conn, path=S2_MIGRATION_FILE)
            _run_migration(conn)
            conn.execute(
                text(
                    """
                    UPDATE public.org_units
                    SET group_id = 2
                    WHERE code = 'COMPL'
                    """
                )
            )
            conn.execute(
                text(
                    """
                    INSERT INTO public.org_units
                        (name, code, parent_unit_id, group_id, is_active)
                    VALUES ('Unrelated unit', 'UNRELATED', 1, 3, TRUE)
                    """
                )
            )

            _run_migration(conn, operation="downgrade")

            remaining_codes = set(
                conn.execute(
                    text(
                        """
                        SELECT code
                        FROM public.org_units
                        WHERE code IN ('TRANSFUSE', 'Amb_chem', 'COMPL', 'UNRELATED')
                        """
                    )
                ).scalars()
            )
            assert remaining_codes == {"TRANSFUSE", "COMPL", "UNRELATED"}
