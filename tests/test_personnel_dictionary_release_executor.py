def initialize(db):
    source,target,_=fixture()
    target['dictionaries']['positions']['rows'][0]['category']='other'
    source['dictionaries']['positions']['rows'].append({**source['dictionaries']['positions']['rows'][0],
        'position_id':543210,'name':'TEST new position','category':'technical','translation_status':'confirmed'})
    source['dictionaries']['position_job_catalog']['rows'].append({'position_id':543210,'job_code':'TEST'})
    with db.begin() as conn:
        conn.exec_driver_sql("""CREATE TABLE positions(position_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,name text,category text,name_kk text,document_nominative_ru text,document_possessive_kk text,translation_status text,document_form_status text,record_kind text,revision integer DEFAULT 1);
          CREATE TABLE job_positions_catalog(job_code text PRIMARY KEY,job_nameru text,job_namekk text,job_namekk_doc text);
          CREATE TABLE position_job_catalog(position_id bigint PRIMARY KEY REFERENCES positions,job_code text REFERENCES job_positions_catalog);
          CREATE TABLE position_aliases(alias_id bigserial PRIMARY KEY,position_id bigint REFERENCES positions,alias_text text,normalized_alias text UNIQUE);
          CREATE TABLE medical_specialty_groups(group_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,code text UNIQUE,name text,is_active boolean);
          CREATE TABLE medical_specialties(medical_specialty_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,group_id bigint REFERENCES medical_specialty_groups,code text,name text,name_kk text,is_active boolean);
          CREATE TABLE alembic_version(version_num text PRIMARY KEY);INSERT INTO alembic_version VALUES('poprint001');
          CREATE VIEW position_directory AS SELECT * FROM positions;
          COMMENT ON VIEW position_directory IS 'posdir001:forms-needs-review:v2';
          CREATE TABLE employees(employee_id bigint PRIMARY KEY,position_id bigint REFERENCES positions);
          CREATE TABLE personnel_orders(order_id bigint PRIMARY KEY,payload jsonb);""")
        for table in ('job_positions_catalog','positions','position_job_catalog','position_aliases','medical_specialty_groups','medical_specialties'):
            for row in target['dictionaries'][table]['rows']:
                keys=list(row)
                conn.execute(text(f'INSERT INTO {table} ('+','.join(keys)+') OVERRIDING SYSTEM VALUE VALUES ('+','.join(':'+k for k in keys)+')'),row)
        conn.exec_driver_sql("INSERT INTO employees VALUES(100,900);INSERT INTO personnel_orders VALUES(100,'{\"marker\":\"SYNTHETIC frozen\"}')")
    approvals=category_change_approval()
    with db.connect() as conn:plan=prepare_plan(source,read_state(conn),approvals)
    assert not plan['global_blockers']
    return source,approvals,plan


def test_apply_is_addressed_preserves_id_foreign_keys_and_repeats_without_writes(fresh_database):
    inventory,approvals,plan=initialize(fresh_database)
    with fresh_database.connect() as conn:before=protected_hashes(conn)
    with fresh_database.begin() as conn:result=apply_approved(conn,plan,inventory,approvals,execute=True)
    assert result['applied'] and result['protected_before']==result['protected_after']==before
    with fresh_database.begin() as conn:
        assert conn.exec_driver_sql('SELECT category FROM positions WHERE position_id=900').scalar()=='technical'
        new=conn.exec_driver_sql("SELECT position_id,translation_status FROM positions WHERE name='TEST new position'").one()
        assert new[0]!=543210 and new[1]=='needs_review'
        assert conn.exec_driver_sql('SELECT position_id FROM employees WHERE employee_id=100').scalar()==900
        state=read_state(conn)['dictionaries']
        repeat=apply_approved(conn,plan,inventory,approvals,execute=True)
        assert repeat['already_applied'] and read_state(conn)['dictionaries']==state


def test_default_dry_run_is_valid_in_readonly_transaction(fresh_database):
    inventory,approvals,plan=initialize(fresh_database)
    with fresh_database.connect() as conn:
        conn.exec_driver_sql('SET TRANSACTION READ ONLY')
        before=read_state(conn)['dictionaries']
        assert not apply_approved(conn,plan,inventory,approvals)['applied']
        assert read_state(conn)['dictionaries']==before


def test_failure_rolls_back_and_target_drift_is_not_overwritten(fresh_database):
    inventory,approvals,plan=initialize(fresh_database)
    with fresh_database.connect() as conn:before=read_state(conn)['dictionaries']
    def fail(_):raise RuntimeError('SYNTHETIC failure')
    with pytest.raises(RuntimeError,match='SYNTHETIC'):
        with fresh_database.begin() as conn:apply_approved(conn,plan,inventory,approvals,execute=True,after_write=fail)
    with fresh_database.connect() as conn:assert read_state(conn)['dictionaries']==before
    with fresh_database.begin() as conn:conn.exec_driver_sql('UPDATE positions SET revision=revision+1 WHERE position_id=900')
    with pytest.raises(RuntimeError,match='drift'):
        with fresh_database.begin() as conn:apply_approved(conn,plan,inventory,approvals,execute=True)


def test_protected_table_trigger_side_effect_forces_rollback(fresh_database):
    inventory,approvals,plan=initialize(fresh_database)
    with fresh_database.begin() as conn:
        conn.exec_driver_sql("""CREATE FUNCTION synthetic_side_effect() RETURNS trigger LANGUAGE plpgsql AS $$BEGIN
          INSERT INTO personnel_orders VALUES(200,'{"marker":"UNEXPECTED"}');RETURN NEW;END$$;
          CREATE TRIGGER synthetic_side_effect AFTER UPDATE ON positions FOR EACH ROW EXECUTE FUNCTION synthetic_side_effect();""")
    with fresh_database.connect() as conn:before=read_state(conn)['dictionaries'];protected=protected_hashes(conn)
    with pytest.raises(RuntimeError,match='Protected'):
        with fresh_database.begin() as conn:apply_approved(conn,plan,inventory,approvals,execute=True)
    with fresh_database.connect() as conn:
        assert read_state(conn)['dictionaries']==before and protected_hashes(conn)==protected


def test_historical_plan_or_changed_approval_is_rejected(fresh_database):
    inventory,approvals,plan=initialize(fresh_database)
    invalid=deepcopy(plan);invalid['format']='personnel-dictionary-proposal-v1'
    with pytest.raises(RuntimeError,match='Historical'):
        with fresh_database.begin() as conn:apply_approved(conn,invalid,inventory,approvals,execute=True)
    changed=deepcopy(approvals);changed['position_category_decisions'][0]['target_category']='other'
    with pytest.raises(RuntimeError,match='approvals changed'):
        with fresh_database.begin() as conn:apply_approved(conn,plan,inventory,changed,execute=True)
    invalid=deepcopy(plan);invalid['target_database']='another_test_database'
    with pytest.raises(RuntimeError,match='another database'):
        with fresh_database.begin() as conn:apply_approved(conn,invalid,inventory,approvals,execute=True)


